/** "4 rabbits on display" and the like: a resident's zoo goal in words (0.1.220). */
export function unlockWords(u) {
  if (u.words) return u.words; // 0.1.243: a goal of one reads better in its own words
  switch (u.kind) {
    case "quest": // 0.1.319: unlocked by a story, not the zoo (Damien); always in its own words
      return "a story";
    case "staffRooms": // 0.1.361
      return "a working Staff Room";
    case "species":
      return `${u.count} different species on display`;
    case "animals":
      return `${u.count} animals on display`;
    case "of":
      return `${u.count} ${u.plural} on display`;
    case "young":
      return `${u.count} young animals on display at once`;
    case "kind":
      return `${u.count} different ${LIKE_NAMES[u.tag] ?? u.tag} on display`;
    case "speciesOf": // 0.1.267
      return `${u.count} different ${u.plural} on display`;
    case "exhibits":
      return u.unique ? `${u.count} exhibits of different species` : `${u.count} exhibits with animals in them`;
    // 0.1.258 (residents/goalRules.js)
    case "cleanStreak":
      return `every exhibit clean for ${u.count} park days in a row`;
    case "staffStreak":
      return `every employee happy (paid) for ${u.count} park days in a row`;
    case "problems":
      return `${u.count} zoo problems: escapes, sick animals or unpaid staff`;
    case "enriched":
      return `${u.count} exhibits with enrichment equipment`;
    default:
      return "";
  }
}
